"""
CAP 1.2 (Common Alerting Protocol, OASIS) export of WeatherGPT alerts.

One <alert> per request, one <info> block per WeatherGPT alert. Every block
says the alert is generated by WeatherGPT from Open-Meteo data and is not an
official IMD warning (senderName, description and the alert <note>).
Built with ElementTree, so text is escaped.
"""

from __future__ import annotations

import uuid
import xml.etree.ElementTree as ET
from datetime import datetime, timedelta, timezone
from typing import Iterable

from models.alerts import WeatherAlert

CAP_NS = "urn:oasis:names:tc:emergency:cap:1.2"
DISCLAIMER = "Generated by WeatherGPT from Open-Meteo forecast data; not an official IMD warning."
SENDER = "weathergpt@weathergpt.invalid"
SENDER_NAME = "WeatherGPT (automated guidance, not IMD)"
VALID_HOURS = 12
AREA_RADIUS_KM = 10

# WeatherGPT level -> CAP severity / urgency / response
_SEVERITY = {"severe": "Extreme", "warning": "Severe", "watch": "Moderate", "advisory": "Minor"}
_URGENCY = {"severe": "Immediate", "warning": "Immediate", "watch": "Expected", "advisory": "Future"}
_RESPONSE = {"severe": "Prepare", "warning": "Prepare", "watch": "Monitor", "advisory": "Monitor"}


def _iso(dt: datetime) -> str:
    # CAP dateTime: no fractional seconds, explicit offset (no "Z").
    return dt.astimezone(timezone.utc).replace(microsecond=0).isoformat()


def _sub(parent: ET.Element, tag: str, text: str | None = None) -> ET.Element:
    el = ET.SubElement(parent, f"{{{CAP_NS}}}{tag}")
    if text is not None:
        el.text = text
    return el


def build_cap(
    alerts: Iterable[WeatherAlert],
    latitude: float,
    longitude: float,
    area_name: str,
    now: datetime | None = None,
    language: str = "en-IN",
) -> str:
    now = now or datetime.now(timezone.utc)
    alerts = list(alerts)
    ET.register_namespace("", CAP_NS)
    root = ET.Element(f"{{{CAP_NS}}}alert")
    _sub(root, "identifier", f"urn:uuid:{uuid.uuid4()}")
    _sub(root, "sender", SENDER)
    _sub(root, "sent", _iso(now))
    _sub(root, "status", "Actual")
    _sub(root, "msgType", "Alert")
    _sub(root, "scope", "Public")
    _sub(root, "note", DISCLAIMER + (" No active alerts for this area." if not alerts else ""))

    for a in alerts:
        info = _sub(root, "info")
        _sub(info, "language", language)
        _sub(info, "category", "Met")
        _sub(info, "event", a.condition)
        _sub(info, "responseType", _RESPONSE[a.severity])
        _sub(info, "urgency", _URGENCY[a.severity])
        _sub(info, "severity", _SEVERITY[a.severity])
        # model-based thresholds on forecasts: "Likely", never "Observed"
        _sub(info, "certainty", "Likely")
        _sub(info, "senderName", SENDER_NAME)
        _sub(info, "effective", _iso(a.created_at))
        _sub(info, "expires", _iso(a.created_at + timedelta(hours=VALID_HOURS)))
        _sub(info, "headline", a.headline)
        _sub(info, "description", f"{a.description} ({a.time_window}.) {DISCLAIMER}")
        _sub(info, "instruction", a.recommended_action)
        _sub(info, "web", "https://open-meteo.com/")
        for name, value in (
            ("weathergpt:alert_type", a.alert_type),
            ("weathergpt:parameter", a.relevant_parameter),
            ("weathergpt:value", f"{a.relevant_value:g} {a.unit}"),
            ("weathergpt:threshold", f"{a.threshold_value:g} {a.unit}"),
        ):
            p = _sub(info, "parameter")
            _sub(p, "valueName", name)
            _sub(p, "value", value)
        area = _sub(info, "area")
        _sub(area, "areaDesc", area_name)
        # CAP circle: "lat,lon radius_km"
        _sub(area, "circle", f"{latitude:.4f},{longitude:.4f} {AREA_RADIUS_KM}")

    return ET.tostring(root, encoding="unicode", xml_declaration=True)
