"""
Early-warning job: for every subscription, evaluate the deterministic alert
engine at its location and send a Web Push when severity BECOMES high
(a "warning"-level alert appears where there was none). Repeats are not sent
while it stays high; it re-arms once severity drops.

Run it on a schedule (cron / Task Scheduler / a platform scheduler):

    python -m dissemination.job            (from backend/)

or call POST /api/alerts/check with the X-Job-Token header (ALERT_JOB_TOKEN).
"""

from __future__ import annotations

import asyncio
import logging
from dataclasses import dataclass, field
from datetime import datetime, timezone
from typing import Awaitable, Callable, Protocol

from alerts.engine import evaluate_alerts
from dissemination.push import SendStatus, VapidConfig, WebPushSender
from dissemination.store import Subscription, SupabaseSubscriptionStore
from models.alerts import WeatherAlert
from models.weather import WeatherResponse

logger = logging.getLogger(__name__)

DISCLAIMER = "Generated by WeatherGPT, not an official IMD warning."
_RANK = {"none": 0, "advisory": 1, "watch": 2, "warning": 3}


class Store(Protocol):
    async def list(self) -> list[Subscription]: ...
    async def update(self, sub_id: str, fields: dict) -> None: ...
    async def delete(self, sub_id: str) -> None: ...


class Sender(Protocol):
    @property
    def available(self) -> bool: ...
    def send(self, endpoint: str, p256dh: str, auth: str, payload: dict) -> SendStatus: ...


@dataclass
class JobReport:
    checked: int = 0
    became_high: int = 0
    sent: int = 0
    gone: int = 0
    failed: int = 0
    disabled: int = 0
    weather_errors: int = 0
    push_available: bool = False
    details: list[dict] = field(default_factory=list)


def level(alerts: list[WeatherAlert]) -> str:
    return max((a.severity for a in alerts), key=lambda s: _RANK[s], default="none")


def is_high(severity: str) -> bool:
    return severity == "warning"


def payload_for(sub: Subscription, alerts: list[WeatherAlert]) -> dict:
    top = max(alerts, key=lambda a: _RANK[a.severity])
    return {
        "title": f"{top.condition} — {sub.location_name}",
        "body": f"{top.headline} {DISCLAIMER}",
        "url": "/alerts",
        "tag": f"wgpt-{sub.id}",
        "severity": top.severity,
    }


async def run_job(
    store: Store,
    sender: Sender,
    fetch_weather: Callable[[float, float], Awaitable[WeatherResponse]],
) -> JobReport:
    report = JobReport(push_available=sender.available)
    subs = await store.list()
    # One weather fetch per ~1 km cell, however many people subscribed there.
    cells: dict[tuple[float, float], list[Subscription]] = {}
    for s in subs:
        cells.setdefault((round(s.latitude, 2), round(s.longitude, 2)), []).append(s)

    for (lat, lon), group in cells.items():
        try:
            weather = await fetch_weather(lat, lon)
        except Exception as exc:  # one bad cell must not stop the job
            logger.warning("Alert job: weather fetch failed for %s,%s: %s", lat, lon, exc)
            report.weather_errors += len(group)
            continue
        alerts = evaluate_alerts(weather)
        severity = level(alerts)
        for sub in group:
            report.checked += 1
            update: dict = {"last_severity": severity}
            outcome = "unchanged"
            if is_high(severity) and not is_high(sub.last_severity):
                report.became_high += 1
                status = await asyncio.to_thread(sender.send, sub.endpoint, sub.p256dh, sub.auth, payload_for(sub, alerts))
                outcome = status
                if status == "sent":
                    report.sent += 1
                    update["last_notified_at"] = datetime.now(timezone.utc).isoformat()
                elif status == "gone":
                    report.gone += 1
                    await store.delete(sub.id)
                    report.details.append({"id": sub.id, "severity": severity, "outcome": "gone"})
                    continue
                elif status == "failed":
                    report.failed += 1
                    # keep the old level so the next run retries
                    update["last_severity"] = sub.last_severity
                else:
                    report.disabled += 1
                    update["last_severity"] = sub.last_severity
            await store.update(sub.id, update)
            report.details.append({"id": sub.id, "severity": severity, "outcome": outcome})
    return report


async def run_from_env() -> JobReport:
    from env_check import warn_misnamed_env_vars
    from query_service import fetch_validated_weather

    warn_misnamed_env_vars()

    store = SupabaseSubscriptionStore.from_env()
    if store is None:
        raise RuntimeError("SUPABASE_URL and SUPABASE_SERVICE_ROLE_KEY are required for the alert job")
    return await run_job(store, WebPushSender(VapidConfig.from_env()), fetch_validated_weather)


if __name__ == "__main__":
    import json
    from dataclasses import asdict

    from pathlib import Path

    from dotenv import load_dotenv

    load_dotenv(Path(__file__).resolve().parents[1] / ".env")
    logging.basicConfig(level=logging.INFO)
    print(json.dumps(asdict(asyncio.run(run_from_env())), indent=2))
