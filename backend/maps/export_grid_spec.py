"""
Generate the frontend's copy of the map tile plan limits from maps/tiles.py.

The backend's ``tiles.plan()`` is the ONLY rule for which boxes the map grid
and hazard endpoints accept (they answer 422 otherwise). The map checks a box
with the same rule before asking, so a zoomed-out view sends no request and
shows "zoom in" instead. This writes
``weathergpt-web/components/map3d/gridSpec.generated.ts`` with the constants
and sample boxes with the backend's own verdict;
``tests/test_grid_spec_export.py`` fails if the file is out of date, and
``e2e/grid-spec.spec.ts`` checks the TypeScript port against every sample.

Regenerate after changing tiles.py (from the repo root):

    backend/.venv/Scripts/python backend/maps/export_grid_spec.py
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

BACKEND = Path(__file__).resolve().parents[1]
if str(BACKEND) not in sys.path:
    sys.path.insert(0, str(BACKEND))

from maps import tiles as T  # noqa: E402

OUTPUT = BACKEND.parent / "weathergpt-web" / "components" / "map3d" / "gridSpec.generated.ts"


def _fits(box: tuple[float, float, float, float]) -> bool:
    try:
        T.plan(*box, max_points=T.MAX_POINTS)
        return True
    except T.GridSpecError:
        return False


def samples() -> list[dict]:
    boxes: list[tuple[float, float, float, float]] = []
    # views centred on Pune and on a tile corner, from street level to all of India
    for lat, lon in ((18.52, 73.86), (20.0, 80.0), (12.97, 77.59)):
        for half_w, half_h in ((0.15, 0.1), (0.5, 0.35), (1, 0.7), (2, 1.4), (4, 2.8), (6, 4), (8, 5.5), (10, 7), (12, 8), (16, 11), (20, 14), (24, 14), (26, 16), (28, 18), (30, 15), (32, 20), (34, 12), (36, 24), (38, 15), (14, 30), (10, 36)):
            boxes.append((round(lat - half_h, 3), round(lon - half_w, 3), round(lat + half_h, 3), round(lon + half_w, 3)))
    # the zoomed-out first load seen in the browser (422 before this check)
    boxes.append((6.273, 41.555, 37.032, 118.445))
    return [{"box": list(b), "fits": _fits(b)} for b in boxes]


def render() -> str:
    spec = {
        "tilePoints": T.TILE_POINTS,
        "maxPoints": T.MAX_POINTS,
        "stepLadder": list(T.STEP_LADDER),
    }
    return (
        "// GENERATED by backend/maps/export_grid_spec.py from backend/maps/tiles.py. Do not edit.\n"
        "// tests/test_grid_spec_export.py fails if this is stale.\n\n"
        f"export const GRID_SPEC = {json.dumps(spec)} as const\n\n"
        "/** Sample boxes [south, west, north, east] with the backend plan()'s verdict (e2e/grid-spec.spec.ts). */\n"
        f"export const GRID_SPEC_SAMPLES: ReadonlyArray<{{ box: [number, number, number, number]; fits: boolean }}> = {json.dumps(samples())}\n"
    )


def main() -> int:
    OUTPUT.write_text(render(), encoding="utf-8", newline="\n")
    print(f"wrote {OUTPUT}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
