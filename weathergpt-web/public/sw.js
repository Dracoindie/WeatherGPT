/*
 * WeatherGPT service worker.
 *
 * - App shell: "/", "/offline", manifest and icons are precached, plus every
 *   main page (/dashboard, /alerts, /climate, /map, /disaster, /login) and the
 *   /_next/static chunks they reference, so the whole app opens offline
 *   (e.g. venue Wi-Fi down during a demo; see docs/DEMO.md).
 * - Pages: network-first; offline falls back to the cached page, then "/".
 * - /_next/static: cache-first (file names are content-hashed).
 * - Backend GET /api/{weather,forecast,alerts,climate}: network-first, the
 *   last good response per URL is kept for offline viewing. POSTs (chat) and
 *   Supabase are never cached.
 */

const VERSION = 'wgpt-v2'
const SHELL = `${VERSION}-shell`
const ASSETS = `${VERSION}-assets`
const DATA = `${VERSION}-data`
const SHELL_URLS = [
  '/',
  '/offline',
  '/manifest.webmanifest',
  '/icons/icon-192.png',
  '/icons/icon-512.png',
]
// Best effort: a page that fails to fetch never blocks installing the worker.
const PAGE_URLS = ['/dashboard', '/alerts', '/climate', '/map', '/disaster', '/login']
const DATA_PATHS = /\/api\/(weather|forecast|alerts|climate)$/
const MAX_DATA_ENTRIES = 40

async function precache() {
  const shell = await caches.open(SHELL)
  await shell.addAll(SHELL_URLS)
  // Each page's HTML plus the chunks it needs, so an offline cold start can hydrate.
  const assets = await caches.open(ASSETS)
  await Promise.all(
    ['/', ...PAGE_URLS].map(async (page) => {
      try {
        const response = await fetch(page, { cache: 'no-store' })
        if (!response.ok) return
        if (page !== '/') await shell.put(page, response.clone())
        const html = await response.text()
        const chunks = [...new Set(html.match(/\/_next\/static\/[^"'\s)]+/g) || [])]
        await Promise.all(chunks.map((u) => assets.add(u).catch(() => undefined)))
      } catch {
        // best effort
      }
    })
  )
}

self.addEventListener('install', (event) => {
  event.waitUntil(precache().then(() => self.skipWaiting()))
})

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches
      .keys()
      .then((keys) => Promise.all(keys.filter((k) => !k.startsWith(VERSION)).map((k) => caches.delete(k))))
      .then(() => self.clients.claim())
  )
})

// The page sends the static chunks it loaded before this worker controlled it.
self.addEventListener('message', (event) => {
  const data = event.data || {}
  if (data.type !== 'cache-urls' || !Array.isArray(data.urls)) return
  const urls = data.urls.filter((u) => {
    try {
      const url = new URL(u)
      return url.origin === self.location.origin && url.pathname.startsWith('/_next/static/')
    } catch {
      return false
    }
  })
  event.waitUntil(
    caches.open(ASSETS).then((cache) => Promise.all(urls.map((u) => cache.add(u).catch(() => undefined))))
  )
})

async function trim(cacheName, max) {
  const cache = await caches.open(cacheName)
  const keys = await cache.keys()
  for (let i = 0; i < keys.length - max; i++) await cache.delete(keys[i])
}

async function networkFirst(request, cacheName, fallbacks = []) {
  const cache = await caches.open(cacheName)
  try {
    const response = await fetch(request)
    if (response.ok) {
      await cache.delete(request) // re-insert so trim() drops the oldest
      await cache.put(request, response.clone())
      if (cacheName === DATA) trim(DATA, MAX_DATA_ENTRIES)
    }
    return response
  } catch (err) {
    const hit = await cache.match(request, { ignoreVary: true })
    if (hit) return hit
    for (const url of fallbacks) {
      const fb = await caches.match(url)
      if (fb) return fb
    }
    throw err
  }
}

async function cacheFirst(request) {
  const hit = await caches.match(request)
  if (hit) return hit
  const response = await fetch(request)
  if (response.ok) (await caches.open(ASSETS)).put(request, response.clone())
  return response
}

// Early-warning pushes from the backend job (backend/dissemination/job.py).
self.addEventListener('push', (event) => {
  let data = {}
  try {
    data = event.data ? event.data.json() : {}
  } catch {
    data = { body: event.data ? event.data.text() : '' }
  }
  const title = data.title || 'WeatherGPT alert'
  event.waitUntil(
    self.registration.showNotification(title, {
      body: data.body || 'Generated by WeatherGPT, not an official IMD warning.',
      icon: '/icons/icon-192.png',
      badge: '/icons/icon-192.png',
      tag: data.tag || 'wgpt-alert',
      renotify: true,
      data: { url: data.url || '/alerts' },
    })
  )
})

self.addEventListener('notificationclick', (event) => {
  event.notification.close()
  const target = new URL((event.notification.data && event.notification.data.url) || '/alerts', self.location.origin).href
  event.waitUntil(
    self.clients.matchAll({ type: 'window', includeUncontrolled: true }).then((wins) => {
      const open = wins.find((w) => w.url === target)
      return open ? open.focus() : self.clients.openWindow(target)
    })
  )
})

self.addEventListener('fetch', (event) => {
  const { request } = event
  if (request.method !== 'GET') return
  const url = new URL(request.url)

  if (request.mode === 'navigate' && url.origin === self.location.origin) {
    event.respondWith(networkFirst(request, SHELL, ['/', '/offline']))
    return
  }
  if (url.origin === self.location.origin && url.pathname.startsWith('/_next/static/')) {
    event.respondWith(cacheFirst(request))
    return
  }
  if (DATA_PATHS.test(url.pathname)) {
    event.respondWith(networkFirst(request, DATA))
  }
})
