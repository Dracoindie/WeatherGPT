'use client'

/**
 * Subscribe this browser to push alerts for the selected location.
 * Signed-in users only (subscriptions are stored per user with RLS).
 */

import { useCallback, useEffect, useState } from 'react'
import Link from 'next/link'
import { BellPlus, BellRing, LoaderCircle, Trash2 } from 'lucide-react'
import { useAuthContext } from '@/context/AuthContext'
import { useI18n } from '@/context/I18nContext'
import {
  browserSupportsPush,
  deleteAlertSubscription,
  getPushConfig,
  listAlertSubscriptions,
  sendTestAlert,
  subscribeToAlerts,
  type AlertSubscription,
  type PushConfig,
  type TestAlertResult,
} from '@/lib/push'

interface Props {
  location: { name: string; latitude: number; longitude: number } | null
}

export function SubscribeAlerts({ location }: Props) {
  const { user, session } = useAuthContext()
  const { language, t } = useI18n()
  const [testing, setTesting] = useState(false)
  const [testResult, setTestResult] = useState<TestAlertResult | null>(null)
  const [config, setConfig] = useState<PushConfig | null>(null)
  const [subs, setSubs] = useState<AlertSubscription[]>([])
  const [busy, setBusy] = useState(false)
  const [message, setMessage] = useState<string | null>(null)
  const supported = browserSupportsPush()

  const refresh = useCallback(async () => {
    try {
      setSubs(await listAlertSubscriptions())
    } catch {
      // table missing (migration 7 not run) or offline: show none
    }
  }, [])

  useEffect(() => {
    getPushConfig()
      .then(setConfig)
      .catch(() => setConfig({ available: false, vapid_public_key: null, reason: 'Backend unreachable.' }))
  }, [])

  useEffect(() => {
    if (!user) return
    const id = window.setTimeout(() => void refresh(), 0)
    return () => window.clearTimeout(id)
  }, [user, refresh])

  async function subscribe() {
    if (!location || !config?.vapid_public_key) return
    setBusy(true)
    setMessage(null)
    try {
      await subscribeToAlerts(location, config.vapid_public_key, language)
      setMessage(`Subscribed to alerts for ${location.name}.`)
      await refresh()
    } catch (err) {
      setMessage(err instanceof Error ? err.message : 'Could not subscribe.')
    } finally {
      setBusy(false)
    }
  }

  async function sendTest() {
    if (!session?.access_token) return
    setTesting(true)
    setTestResult(null)
    try {
      setTestResult(await sendTestAlert(session.access_token))
    } finally {
      setTesting(false)
    }
  }

  function testMessage(r: TestAlertResult): string {
    switch (r.status) {
      case 'sent':
        return `${t('push.testSent')} (${r.sent}/${r.total})`
      case 'no_subscription':
        return t('push.testNoSub')
      case 'disabled':
        return t('push.testDisabled')
      case 'rate_limited':
        return t('push.testWait')
      case 'failed':
        return t('push.testFailed')
      default:
        return r.message || t('push.testFailed')
    }
  }

  async function remove(id: string) {
    try {
      await deleteAlertSubscription(id)
      await refresh()
    } catch (err) {
      setMessage(err instanceof Error ? err.message : 'Could not remove the subscription.')
    }
  }

  return (
    <div className="rounded-[16px] border border-line bg-panel p-5" aria-label="Push alerts">
      <div className="flex items-center gap-2 font-mono text-[11px] uppercase tracking-wider text-fog">
        <BellPlus className="size-3.5 text-teal" />
        Push alerts
      </div>
      <p className="mt-2 text-xs text-ink-soft">
        Get a notification when a warning-level alert starts for a place. Generated by WeatherGPT, not official IMD
        warnings.
      </p>

      {!user ? (
        <p className="mt-3 text-sm text-ink">
          <Link href="/login" className="text-teal underline-offset-2 hover:underline">
            Sign in
          </Link>{' '}
          to subscribe.
        </p>
      ) : !supported ? (
        <p className="mt-3 text-sm text-ink-soft">This browser does not support push notifications.</p>
      ) : !config?.vapid_public_key ? (
        <p className="mt-3 text-sm text-ink-soft">{config ? config.reason : 'Checking…'}</p>
      ) : (
        <>
          <button
            type="button"
            onClick={() => void subscribe()}
            disabled={!location || busy}
            className="mt-3 inline-flex min-h-11 w-full items-center justify-center gap-2 rounded-md bg-ink px-4 text-sm text-panel disabled:opacity-50"
          >
            {busy ? <LoaderCircle className="size-4 animate-spin" /> : <BellPlus className="size-4" />}
            {location ? `Alert me for ${location.name.split(',')[0]}` : 'Pick a location first'}
          </button>
          {!config.available && config.reason && <p className="mt-2 text-[11px] text-amber">{config.reason}</p>}
        </>
      )}

      {message && <p className="mt-2 text-xs text-ink" role="status">{message}</p>}

      {subs.length > 0 && (
        <ul className="mt-3 space-y-1.5">
          {subs.map((s) => (
            <li key={s.id} className="flex items-center justify-between gap-2 text-xs">
              <span className="truncate text-ink">{s.location_name}</span>
              <button
                type="button"
                onClick={() => void remove(s.id)}
                aria-label={`Stop alerts for ${s.location_name}`}
                className="grid size-9 place-items-center rounded-md text-ink-soft hover:bg-canvas hover:text-ink"
              >
                <Trash2 className="size-3.5" />
              </button>
            </li>
          ))}
        </ul>
      )}

      {user && session?.access_token && subs.length > 0 && (
        <div className="mt-4 border-t border-line/60 pt-3">
          <button
            type="button"
            onClick={() => void sendTest()}
            disabled={testing}
            className="inline-flex min-h-11 w-full items-center justify-center gap-2 rounded-md border border-line px-4 text-sm text-ink hover:bg-canvas disabled:opacity-50"
          >
            {testing ? <LoaderCircle className="size-4 animate-spin" /> : <BellRing className="size-4" />}
            {testing ? t('push.testSending') : t('push.test')}
          </button>
          <p className="mt-1.5 text-[11px] text-ink-soft">{t('push.testNote')}</p>
          {testResult && (
            <p
              role="status"
              data-test-status={testResult.status}
              className={`mt-1.5 text-xs ${testResult.status === 'sent' ? 'text-teal' : 'text-amber'}`}
            >
              {testMessage(testResult)}
            </p>
          )}
        </div>
      )}
    </div>
  )
}
