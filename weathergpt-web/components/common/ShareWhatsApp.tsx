'use client'

import { Share2 } from 'lucide-react'
import { cn } from '@/lib/utils'

export const NOT_OFFICIAL = 'Generated by WeatherGPT, not an official IMD warning.'

/** wa.me link with the text plus the not-official label (and the app link). */
export function whatsAppHref(text: string, url?: string): string {
  const parts = [text.trim(), `— ${NOT_OFFICIAL}`]
  if (url) parts.push(url)
  return `https://wa.me/?text=${encodeURIComponent(parts.join('\n'))}`
}

export function ShareWhatsApp({
  text,
  url,
  tone = 'light',
  className,
}: {
  text: string
  url?: string
  tone?: 'light' | 'sky'
  className?: string
}) {
  const href = whatsAppHref(text, url ?? (typeof window !== 'undefined' ? window.location.origin : undefined))
  return (
    <a
      href={href}
      target="_blank"
      rel="noopener noreferrer"
      className={cn(
        'inline-flex min-h-9 items-center gap-1.5 rounded-full border px-3 text-xs font-medium transition-colors',
        tone === 'sky'
          ? 'border-emerald-400/40 bg-emerald-400/10 text-emerald-200 hover:bg-emerald-400/20'
          : 'border-emerald-600/30 bg-emerald-50 text-emerald-800 hover:bg-emerald-100 dark:bg-emerald-900/20 dark:text-emerald-200',
        className
      )}
    >
      <Share2 className="size-3.5" aria-hidden="true" />
      Share on WhatsApp
    </a>
  )
}
