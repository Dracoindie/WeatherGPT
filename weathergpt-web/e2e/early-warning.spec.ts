import { expect, test } from '@playwright/test'
import { enterDemo, mockBackend, PUNE } from './support/mockApi'

/** Early-warning dissemination UI: labels, CAP export, WhatsApp sharing, push opt-in. */

test('alerts page labels alerts as unofficial and offers CAP + WhatsApp', async ({ page, context }) => {
  await context.grantPermissions(['geolocation'])
  await context.setGeolocation({ latitude: PUNE.latitude, longitude: PUNE.longitude })
  await mockBackend(page, { routes: { '/api/push/config': { available: false, vapid_public_key: null, reason: 'VAPID keys are not configured on the server.' } } })
  await enterDemo(page)
  await page.locator('a[href="/alerts"]').first().dispatchEvent('click')
  await page.waitForURL('**/alerts')
  await page.getByRole('button', { name: /use my current location/i }).first().click()

  const card = page.getByRole('article').filter({ hasText: 'Heavy rain expected' })
  await expect(card).toBeVisible()
  await expect(card.getByText('Generated by WeatherGPT, not an official IMD warning.')).toBeVisible()
  await expect(page.getByText('Generated by WeatherGPT, not official IMD warnings.').first()).toBeVisible()

  const share = card.getByRole('link', { name: /share on whatsapp/i })
  const href = decodeURIComponent((await share.getAttribute('href'))!)
  expect(href).toContain('https://wa.me/?text=')
  expect(href).toContain('Heavy rain expected')
  expect(href).toContain('not an official IMD warning')

  const cap = page.getByRole('link', { name: /download alerts \(cap 1\.2 xml\)/i })
  const capHref = (await cap.getAttribute('href'))!
  expect(capHref).toContain('/api/alerts/cap?latitude=')
  expect(capHref).toContain(`latitude=${PUNE.latitude}`)

  // Push opt-in needs an account; demo mode has none.
  await expect(page.getByRole('link', { name: 'Sign in' }).last()).toBeVisible()
})

test('a chat answer can be shared on WhatsApp', async ({ page }) => {
  await mockBackend(page)
  await page.goto('/')
  const input = page.getByRole('textbox', { name: /ask about the weather/i })
  await input.fill('Will it rain in Pune tomorrow?')
  await input.press('Enter')
  const share = page.getByRole('link', { name: /share on whatsapp/i })
  await expect(share).toBeVisible({ timeout: 20_000 })
  const text = decodeURIComponent((await share.getAttribute('href'))!.split('text=')[1])
  expect(text).toContain('Will it rain in Pune tomorrow?')
  expect(text).toContain('12.4 mm')
  expect(text).toContain('not an official IMD warning')
})

test('service worker shows pushes and opens the alerts page on click', async ({ request }) => {
  const sw = await (await request.get('/sw.js')).text()
  expect(sw).toContain("addEventListener('push'")
  expect(sw).toContain("addEventListener('notificationclick'")
  expect(sw).toContain('not an official IMD warning')
})
