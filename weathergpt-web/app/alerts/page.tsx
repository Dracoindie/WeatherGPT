'use client'

import { useCallback, useState } from 'react'
import { FileDown, ShieldAlert } from 'lucide-react'
import AuthGuard from '@/components/auth/AuthGuard'
import { AppShell } from '@/components/ui/AppShell'
import { PageHeader } from '@/components/ui/PageHeader'
import { SkyLinkButton } from '@/components/ui/SkyButton'
import LocationPicker, { type LocationData } from '@/components/location/LocationPicker'
import { AlertList } from '@/components/alerts/AlertList'
import { SubscribeAlerts } from '@/components/alerts/SubscribeAlerts'
import { ThresholdTable } from '@/components/alerts/ThresholdTable'
import { TrustStrip } from '@/components/common/TrustStrip'
import { useI18n } from '@/context/I18nContext'
import { fetchAlerts } from '@/lib/api/alerts'
import { API_BASE } from '@/lib/api/base'
import type { WeatherAlert } from '@/types/alerts'

export default function AlertsPage() {
  const { t } = useI18n()
  const [location, setLocation] = useState<LocationData | null>(null)
  const [alerts, setAlerts] = useState<WeatherAlert[]>([])
  const [loading, setLoading] = useState(false)
  const [error, setError] = useState<string | null>(null)

  const handleLocationSelected = useCallback(async (loc: LocationData) => {
    setLocation(loc)
    setLoading(true)
    setError(null)
    try {
      const data = await fetchAlerts({ latitude: loc.latitude, longitude: loc.longitude })
      setAlerts(data.alerts)
    } catch (err: unknown) {
      setError(err instanceof Error ? err.message : 'Failed to fetch weather alerts.')
      setAlerts([])
    } finally {
      setLoading(false)
    }
  }, [])

  return (
    <AppShell>
      <AuthGuard>
        <PageHeader
          eyebrow={t('alerts.eyebrow')}
          icon={<ShieldAlert className="size-3.5" />}
          title={t('alerts.heading')}
          description={
            <>
              <p>{t('alerts.intro')}</p>
              <p className="mt-1 font-medium text-hud">Generated by WeatherGPT, not official IMD warnings.</p>
            </>
          }
          actions={<LocationPicker onLocationSelected={handleLocationSelected} defaultLocation={location} />}
        />

        <div className="grid gap-5 lg:grid-cols-[minmax(0,1fr)_360px]">
          <section aria-label="Active meteorological alerts" className="min-w-0">
            {location || loading ? (
              <AlertList alerts={alerts} locationName={location?.name} loading={loading} error={error} />
            ) : (
              <div className="sky-glass p-8 text-center text-sm text-hud-dim">{t('alerts.pickFirst')}</div>
            )}
          </section>

          <aside className="min-w-0 space-y-5">
            <SubscribeAlerts location={location} />
            {location && (
              <SkyLinkButton
                href={`${API_BASE}/api/alerts/cap?latitude=${location.latitude}&longitude=${location.longitude}&name=${encodeURIComponent(location.name)}`}
                variant="subtle"
                className="w-full"
                aria-label="Download alerts (CAP 1.2 XML)"
              >
                <FileDown className="size-4 text-accent-text" />
                {t('alerts.cap')}
              </SkyLinkButton>
            )}
            <ThresholdTable />
            <TrustStrip />
          </aside>
        </div>
      </AuthGuard>
    </AppShell>
  )
}
